<script lang="ts">
  import ErrorNote from "../components/ErrorNote.svelte";
  import Icon from "../components/Icon.svelte";
  import PageHead from "../components/PageHead.svelte";
  import { dur, mb } from "../format";
  import { strings } from "../i18n";
  import { app, receiveAddress, receiveStart, receiveStop, receiveUse } from "../state.svelte";

  /** Tips once the phone hasn't opened the page this long after it started (oopz-app's receive::TIPS_AFTER). */
  const TIPS_AFTER_MS = 45_000;

  let t = $derived(strings(app.lang));
  let rx = $derived(app.receive);
  let copied = $state(false);
  // The status changes every half second, so this is looked at again as often.
  let stuck = $derived(!!rx && rx.status.running && !rx.status.opened && rx.status.files.length === 0 && Date.now() - rx.started >= TIPS_AFTER_MS);
  // Another address only before anything arrived: picking one starts the page again.
  let canMove = $derived(!!rx && rx.status.running && rx.info.addresses.length > 1 && rx.status.files.length === 0 && !rx.status.current);

  async function copy(url: string) {
    try {
      await navigator.clipboard.writeText(url);
      copied = true;
      setTimeout(() => (copied = false), 1500);
    } catch {
      // No clipboard: the address is shown and can be selected.
    }
  }
</script>

<div class="page">
  <PageHead title={t.fromWifi} sub={t.fromWifiText} />
  <ErrorNote error={app.error} />

  {#if !rx}
    <div class="panel start">
      <Icon name="wifi" size={32} />
      <p>{t.wifiWhere}</p>
      <button class="btn primary" disabled={app.busy} onclick={receiveStart}><Icon name="folder" />{t.startWifi}</button>
    </div>
    <div class="note warn"><Icon name="alert" /><span>{t.wifiWarn}</span></div>
  {:else}
    {@const s = rx.status}
    <div class="split" class:solo={!s.running}>
      {#if s.running}
        <div class="qr-card">
          <!-- Generated by our own Rust code from our own address: no outside text in it. -->
          <div class="qr" role="img" aria-label={t.qrLabel}>{@html rx.info.qr_svg}</div>
          <p class="scan">{t.wifiScan}</p>
          <p class="hint">{t.wifiOr}</p>
          <div class="url">
            <code>{rx.info.url}</code>
            <button class="btn small icon-only" aria-label={t.copy} title={t.copy} onclick={() => copy(rx.info.url)}>
              <Icon name={copied ? "check" : "paste"} size={16} />
            </button>
          </div>
          {#if canMove}
            <label class="address">
              <span>{t.wifiAddress}</span>
              <select class="select" value={rx.info.ip} disabled={app.busy} onchange={(e) => receiveAddress(e.currentTarget.value)}>
                {#each rx.info.addresses as a (a.ip)}
                  <option value={a.ip}>{a.ip}{a.card ? ` · ${a.card}` : ""}{a.likely_virtual ? ` (${t.wifiVirtual})` : ""}</option>
                {/each}
              </select>
            </label>
            <p class="hint">{t.wifiAddressHint}</p>
          {/if}
        </div>
      {/if}
      <div class="status" aria-live="polite">
        {#if s.running && !s.current && s.files.length === 0}
          {#if s.opened}
            <p class="waiting"><Icon name="check" class="ok-ico" />{t.wifiOpened}</p>
          {:else}
            <p class="waiting"><Icon name="wifi" />{t.wifiWaiting}</p>
          {/if}
        {/if}
        {#if stuck}
          <div class="note">
            <Icon name="info" />
            <div>
              <p class="tips-title">{t.wifiTipsTitle}</p>
              <ul class="tips">
                {#each t.wifiTips as tip (tip)}<li>{tip}</li>{/each}
                {#if canMove}<li>{t.wifiTipOther}</li>{/if}
              </ul>
            </div>
          </div>
        {/if}
        {#if s.current}
          {@const c = s.current}
          <div class="file-progress">
            <p><span>{t.wifiReceiving}: <strong>{c.name}</strong> · {mb(c.total)}</span><span class="pct">{Math.round((c.done / (c.total || 1)) * 100)}%</span></p>
            <progress max={c.total || 1} value={c.done} aria-label="{t.wifiReceiving} {c.name}"></progress>
            <!-- Changes every half second: not read out. -->
            <p class="pace" aria-live="off">
              {#if c.bytes_per_sec > 0}<span>{t.wifiPace}: {mb(c.bytes_per_sec)}/s</span>{/if}
              {#if c.secs_left !== null}<span>{t.secsLeft(c.secs_left)}</span>{/if}
            </p>
          </div>
        {/if}
        {#if s.running && !s.current && s.idle_secs_left > 0}
          <p class="pace" aria-live="off">{t.wifiIdleLeft(dur(s.idle_secs_left))}</p>
        {/if}
        {#if s.files.length > 0}
          <h2 class="h3">{t.wifiReceived}</h2>
          <ul class="inset">
            {#each s.files as f (f.name)}
              <li class="row"><Icon name="check" class="ok-ico" /><span class="grow">{f.name}</span><span class="muted">{mb(f.bytes)}</span></li>
            {/each}
          </ul>
        {/if}
        <p class="free"><Icon name="download" />{t.wifiFree}: {mb(rx.info.free)}</p>
        {#if s.running}<div class="note warn"><Icon name="alert" /><span>{t.wifiWarn}</span></div>{/if}
        {#if s.stopped}<p>{t.wifiStopped[s.stopped] ?? s.stopped}</p>{/if}
        <div class="row-buttons">
          {#if s.files.length > 0}<button class="btn primary" onclick={receiveUse}>{t.wifiUseThese}</button>{/if}
          {#if s.running}<button class="btn" onclick={receiveStop}>{t.wifiStop}</button>{/if}
          {#if !s.running}<button class="btn" onclick={() => (app.receive = null)}>{t.wifiAgain}</button>{/if}
        </div>
      </div>
    </div>
  {/if}
</div>

